class Employee:

    language = " py" # This is a class attribute

    salary = 120000000 



prince = Employee()

prince.name = "Prince" # THis is an instance attribute

print(prince.name,prince.salary, prince.language)



rohan= Employee()

rohan.name= "rohan robin"

print(rohan.name,rohan.salary, rohan.language)



# Here name is instance attribute and salary and language are class attribute as they directly belong to the class
